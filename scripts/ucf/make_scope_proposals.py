#!/usr/bin/env python3
"""
Re-key the ISO scope applicability proposals from Annex A ids to unified control ids.

    python scripts/ucf/make_scope_proposals.py [--data DIR]

Reads the proposals in app/frameworks/definitions/iso27001.py (read only; wiring is WP 5.5) and the
library mappings. For each (question, answer), a unified control is proposed as likely not
applicable only when every record it carries is one of that answer's Annex A ids. A control that
also carries a clause 4 to 10 record, another Annex A record, or a NIST or DPDPA record is held back
and listed in notes_scope_rekey.md for Saqlain.

Writes <data>/scope_proposals.csv (columns in FORMAT.md) and <data>/notes_scope_rekey.md.
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import validate  # noqa: E402  (also puts the repo root on sys.path)

from app.frameworks.definitions.iso27001 import ISO27001_DEFINITION  # noqa: E402
from app.frameworks.ucf.loader import Library, load_library  # noqa: E402

COLUMNS = ("question", "answer", "unified_control_id", "source_records", "reason")


def carried_records(lib: Library, cid: str) -> set[str]:
    return set(lib.records_of_control.get(cid, set()))


def blockers(lib: Library, cid: str, excludable: set[str]) -> list[str]:
    """Why a control cannot be proposed, one phrase per kind of blocking record."""
    out = []
    for rid in sorted(carried_records(lib, cid) - excludable):
        rec = lib.records.get(rid)
        fw = rec.framework if rec else "?"
        if fw == "iso27001" and rec and rec.kind == "clause":
            out.append(f"{rid} (clause, never excludable)")
        elif fw == "iso27001":
            out.append(f"{rid} (Annex A, not excluded by this answer)")
        else:
            out.append(f"{rid} ({'NIST' if fw == 'nist_csf' else 'DPDPA'} record needs it)")
    return out


def short(rid: str) -> str:
    return rid.replace("ISO.A", "A.")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Re-key ISO scope proposals to unified controls.")
    ap.add_argument("--data", default=str(validate.DEFAULT_DATA), help="data folder (default docs/ucf/drafts)")
    args = ap.parse_args(argv)
    lib = load_library(args.data)
    for err in lib.load_errors:
        print(f"WARN {err}")

    labels = {(q.id, o["value"]): o["label"].replace(" \u2014 ", ": ") for q in ISO27001_DEFINITION.scope_questions for o in q.options}
    rows: list[dict] = []
    held: list[tuple[str, str, str, str, list[str]]] = []
    lost: list[tuple[str, str, str]] = []  # Annex id whose every control is held back
    for p in ISO27001_DEFINITION.applicability_proposals:
        excludable = set(p.control_ids)
        for answer in p.answers:
            for rid in p.control_ids:
                cids = sorted(lib.controls_of_record.get(rid, set()))
                clean = 0
                for cid in cids:
                    block = blockers(lib, cid, excludable)
                    if block:
                        held.append((p.scope_question_id, answer, cid, rid, block))
                        continue
                    if any(r["question"] == p.scope_question_id and r["answer"] == answer
                           and r["unified_control_id"] == cid for r in rows):
                        clean += 1
                        continue
                    src = sorted(carried_records(lib, cid))
                    rows.append({
                        "question": p.scope_question_id,
                        "answer": answer,
                        "unified_control_id": cid,
                        "source_records": " ".join(src),
                        "reason": (f"Answer \"{labels.get((p.scope_question_id, answer), answer)}\": "
                                   f"the control \"{lib.controls[cid].title}\" draws only on {', '.join(short(s) for s in src)}, "
                                   "which this answer makes likely not applicable. The consultant confirms."),
                    })
                    clean += 1
                if not clean:
                    lost.append((p.scope_question_id, answer, rid))

    data = Path(args.data)
    with (data / "scope_proposals.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLUMNS, quoting=csv.QUOTE_ALL)
        w.writeheader()
        w.writerows(rows)

    notes = [
        "# Scope proposals: cases that are no longer clean",
        "",
        "Generated by scripts/ucf/make_scope_proposals.py; do not edit by hand.",
        "",
        "The ISO scope answers propose Annex A controls as likely not applicable. After re-keying, a unified "
        "control is proposed only when every record it carries is excluded by the same answer. The controls "
        "below also carry another record, so they are held back.",
        "",
        "| Question | Answer | Unified control | Reached from | Also carries |",
        "|---|---|---|---|---|",
    ]
    for q, a, cid, rid, block in held:
        notes.append(f"| {q} | {a} | {cid} {lib.controls[cid].title} | {short(rid)} | {'; '.join(block)} |")
    notes += ["", "## Annex A ids with no clean unified control left", ""]
    notes += [f"- {q} = {a}: {short(rid)} (every control it maps to is held back above)" for q, a, rid in lost] or ["None."]
    notes.append("")
    (data / "notes_scope_rekey.md").write_text("\n".join(notes), encoding="utf-8")

    print(f"wrote {len(rows)} proposals to {data / 'scope_proposals.csv'}")
    print(f"held back {len(held)} (question, answer, control) cases; {len(lost)} Annex A ids lost every control")
    for q, a, cid, rid, block in held:
        print(f"  held {q}={a} {cid} via {short(rid)}: {'; '.join(block)}")
    for q, a, rid in lost:
        print(f"  lost {q}={a} {short(rid)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
